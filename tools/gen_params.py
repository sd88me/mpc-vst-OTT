#!/usr/bin/env python3
"""vst/params.json + vst/presets.json -> src/params_gen.h (the native front end's table) and params.lock.

The VST order is the released 1.0.1 wrapper build's: the 18 keys of vst/params.json, which must equal vst/params.lock
(tests/check_legacy.sh builds the release itself). 1.0.1 had no hidden popup flags. New parameters are appended after
index 17 and listed in ./params.lock, which must keep its existing order (append only):
  18 fav_add, 19 fav_del   SAVE PRESET / DELETE PRESET: store the current settings as a user preset in the PRESET menu, or
                           delete the picked one (plugin-local)
  20 fav_name              the name being typed (text readout)
  21 kb_open               the drawn keyboard is showing (1) or not (0): the skin shows it with IndexedEnabling
  22.. kb_*                the keyboard's keys (momentary): 0-9, A-Z, -, space, delete, shift, cancel, save
  64 h_level, m_level, l_level   each band's output level in dB (-60..0), continuous, for the native Meter widget
  67 h_hold, m_hold, l_hold      its peak hold: the highest level for 1.5 s, then falling 20 dB/s (the skin's Hold/ handle never falls)
"""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst", "params.json")))
P = P["params"] if isinstance(P, dict) else P
PRESETS = json.load(open(os.path.join(ROOT, "vst", "presets.json")))["presets"]
RELEASED = [l.strip() for l in open(os.path.join(ROOT, "vst", "params.lock")) if l.strip() and not l.startswith("#")]

KB_CHARS = "1234567890QWERTYUIOPASDFGHJKLZXCVBNM-"
KB_KEYS = [("kb_" + ("dash" if c == "-" else c.lower()), "Key " + c) for c in KB_CHARS] + \
          [("kb_space", "Key Space"), ("kb_bksp", "Key Delete"), ("kb_shift", "Key Shift"), ("kb_cancel", "Key Cancel"),
           ("kb_save", "Key Save")]
APPENDED = [("fav_add", "Save Preset"), ("fav_del", "Delete Preset"), ("fav_name", "Preset Name"), ("kb_open", "Keyboard")] + KB_KEYS + \
           [("h_level", "High Level"), ("m_level", "Mid Level"), ("l_level", "Low Level")] + \
           [("h_hold", "High Peak Hold"), ("m_hold", "Mid Peak Hold"), ("l_hold", "Low Peak Hold")]
FAV_SLOTS = 32
FAV_NAME_MAX = 20          # the MPC shows 24 characters of a program name; "U01 " takes 4

keys = [p["key"] for p in P]
if keys != RELEASED:
    raise SystemExit("vst/params.json no longer matches vst/params.lock (the 1.0.1 order is frozen)")
order = keys + [k for k, _ in APPENDED]
lock_path = os.path.join(ROOT, "params.lock")
if os.path.exists(lock_path):
    old = [l.strip() for l in open(lock_path) if l.strip() and not l.startswith("#")]
    if order[:len(old)] != old:
        raise SystemExit("params.lock: an existing parameter changed index (append only)")
with open(lock_path, "w") as f:
    f.write("# OTTmpc parameter order: index = VST parameter number = skin binding. Append only.\n")
    f.write("".join(k + "\n" for k in order))

FL = dict(kEngine=1, kMeter=2, kLocal=4, kMomentary=8, kText=16, kUi=32, kNoAuto=64, kChoice=128, kLevel=256)


def F(v):
    t = "%g" % v
    return t + ("f" if ("." in t or "e" in t) else ".0f")


out = ["/* generated by tools/gen_params.py from vst/params.json and vst/presets.json: do not edit. Frozen VST order. */",
       "#pragma once",
       "enum { %s };" % ", ".join("%s = %d" % kv for kv in FL.items()),
       "struct PSpec { const char *key, *name, *unit; float min, max, def; int flags, decimals; const char *const *choices; int nchoices; };",
       ""]
rows = []
neng = 0
for i, p in enumerate(P):
    if "options" in p:   # the band meters: display only, the engine's steps
        out.append("static const char *const ch_%d[] = {%s};" % (i, ", ".join(json.dumps(o) for o in p["options"])))
        rows.append('    {"%s", "%s", "", 0.0f, %s, 0.0f, kMeter | kChoice | kNoAuto, 0, ch_%d, %d},'
                    % (p["key"], p["name"], F(len(p["options"]) - 1), i, len(p["options"])))
    else:
        neng += 1
        span = p["max"] - p["min"]
        dec = 0 if span >= 100 and p["unit"] in ("%", "Hz") else 1
        rows.append('    {"%s", "%s", "%s", %s, %s, %s, kEngine, %d, nullptr, 0},'
                    % (p["key"], p["name"], p["unit"], F(p["min"]), F(p["max"]), F(p["default"]), dec))
for k, name in APPENDED:
    if k.endswith("_level") or k.endswith("_hold"):
        rows.append('    {"%s", "%s", "dB", -60.0f, 0.0f, -60.0f, kLevel | kNoAuto, 1, nullptr, 0},' % (k, name))
    elif k == "fav_name":
        rows.append('    {"%s", "%s", "", 0.0f, 1023.0f, 0.0f, kLocal | kText | kNoAuto, 0, nullptr, 0},' % (k, name))
    elif k == "kb_open":
        rows.append('    {"%s", "%s", "", 0.0f, 1.0f, 0.0f, kLocal | kUi | kNoAuto, 0, nullptr, 0},' % (k, name))
    else:
        rows.append('    {"%s", "%s", "", 0.0f, 1.0f, 0.0f, kLocal | kMomentary | kNoAuto, 0, nullptr, 0},' % (k, name))
out.append("")
out.append("static const PSpec g_pspecs[] = {")
out += rows
out.append("};")
ix = {k: i for i, k in enumerate(order)}
out += [
    "static const int kNumParams = %d;" % len(order),
    "static const int kNumEngineParams = %d;   // 0 .. this - 1 are the engine's settings (then the meters)" % neng,
    "static const int kFirstMeter = %d, kNumMeters = %d;" % (neng, len(P) - neng),
    "static const int kFavAdd = %d, kFavDel = %d, kFavName = %d, kKbOpen = %d, kKbFirst = %d, kKbCount = %d;"
    % (ix["fav_add"], ix["fav_del"], ix["fav_name"], ix["kb_open"], ix[KB_KEYS[0][0]], len(KB_KEYS)),
    "static const int kFirstLevel = %d, kFirstHold = %d;   // h/m/l_level, h/m/l_hold" % (ix["h_level"], ix["h_hold"]),
    "static const char kKbChars[] = \"%s\";   // the character keys from kKbFirst (then space, delete, shift, cancel, save)" % KB_CHARS,
    "static const int kFavSlots = %d, kFavNameMax = %d;" % (FAV_SLOTS, FAV_NAME_MAX),
    "",
    "// the factory presets of 1.x (vst/presets.json): programs 0 .. kNumFactory - 1, values in engine order (unlisted = default)",
    "struct FactoryPreset { const char *name; float values[%d]; };" % neng,
    "static const int kNumFactory = %d;" % len(PRESETS),
    "static const FactoryPreset g_factory[] = {",
]
for pr in PRESETS:
    vals = [pr["values"].get(p["key"], p["default"]) for p in P if "options" not in p]
    out.append('    {%s, {%s}},' % (json.dumps(pr["name"]), ", ".join(F(v) for v in vals)))
out.append("};")
open(os.path.join(ROOT, "src", "params_gen.h"), "w").write("\n".join(out) + "\n")
print("%d params (%d engine, %d meters, %d appended), %d factory presets -> src/params_gen.h, params.lock"
      % (len(order), neng, len(P) - neng, len(APPENDED), len(PRESETS)))
